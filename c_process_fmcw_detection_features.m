        meanAbsoluteVelocityError);

    fprintf("Lowest detected input SNR:       %+6.2f dB\n", ...
        min(input_snr_db(detected)));

end

targetClasses = unique(actual_class);

for classIdx = 1:numel(targetClasses)

    currentClass = targetClasses(classIdx);
    classMask = actual_class == currentClass;

    fprintf("%-6s detection rate: %5.1f%% (%d/%d)\n", ...
        char(currentClass), ...
        100 * nnz(detected(classMask)) / nnz(classMask), ...
        nnz(detected(classMask)), ...
        nnz(classMask));

end

fprintf("Saved feature table to:\n");
fprintf("  %s\n", featureTableFile);

