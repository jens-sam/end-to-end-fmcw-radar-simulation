%% c_process_fmcw_detection_features.m
% Step 6D: Process physics-based FMCW scenarios
%
% Processing chain:
%   Raw physics-based IQ
%      -> MTI clutter removal
%      -> Hann windowing
%      -> Range-Doppler FFT
%      -> Edge-aware 2D CA-CFAR
%      -> Detection clustering
%      -> Strongest-cluster selection
%      -> Feature extraction and truth verification
%
% This Round 3 script is based on the working Step 5 feature extractor.
% It does not use truth range or velocity to gate or select detections.
% Truth is read only after detection to calculate estimation errors.

clear;
clc;
close all;

%% ------------------------------------------------------------------------
% folders
% -------------------------------------------------------------------------

dataDir = "data_round3";
outputDir = "outputs_round3";

if ~isfolder(outputDir)
    mkdir(outputDir);
end

%% ------------------------------------------------------------------------
% Find all physics-based radar scenarios
% -------------------------------------------------------------------------

rawFiles = dir(fullfile(dataDir, "raw_iq_scenario_*.mat"));

if isempty(rawFiles)
    error( ...
        "Step6D:NoFiles", ...
        "No raw IQ scenario files were found in data_round3.");
end

% Sort files so Scenario 001 comes before Scenario 002, etc.
[~, sortOrder] = sort({rawFiles.name});
rawFiles = rawFiles(sortOrder);

numScenarios = numel(rawFiles);

fprintf("Step 6D: Physics-Based FMCW Detection and Feature Extraction\n");
fprintf("------------------------------------------------------------\n");
fprintf("Number of scenarios found: %d\n", numScenarios);
fprintf("Detector selection uses no truth-centered range or velocity gate.\n\n");

%% ------------------------------------------------------------------------
% Preallocate physics, feature, and verification arrays
% -------------------------------------------------------------------------

scenario_id = zeros(numScenarios, 1);
actual_class = strings(numScenarios, 1);
detected = false(numScenarios, 1);

% Physics-based values used to describe the simulated input
received_power_dbm = nan(numScenarios, 1);
input_snr_db = nan(numScenarios, 1);
rcs_m2 = nan(numScenarios, 1);

% Truth values used only for verification after detection
truth_range_m = nan(numScenarios, 1);
truth_velocity_mps = nan(numScenarios, 1);

% Extracted radar features
estimated_range_m = nan(numScenarios, 1);
estimated_velocity_mps = nan(numScenarios, 1);
absolute_speed_mps = nan(numScenarios, 1);
peak_power_db = nan(numScenarios, 1);
estimated_snr_db = nan(numScenarios, 1);
cluster_cfar_cells = nan(numScenarios, 1);

% Detector diagnostics
total_cfar_cells = zeros(numScenarios, 1);
num_clusters = zeros(numScenarios, 1);

% Truth-verification errors
range_error_m = nan(numScenarios, 1);
velocity_error_mps = nan(numScenarios, 1);

%% ------------------------------------------------------------------------
% Process every scenario
% -------------------------------------------------------------------------

for fileIdx = 1:numScenarios

    %% Load current scenario

    rawFile = fullfile(dataDir, rawFiles(fileIdx).name);

    radarData = load(rawFile, "iq", "scene", "params");

    iq = radarData.iq;
    scene = radarData.scene;
    params = radarData.params;

    %% Read scenario number from filename

    scenarioToken = regexp( ...
        rawFiles(fileIdx).name, ...
        "(\d+)\.mat$", ...
        "tokens", ...
        "once");

    if isempty(scenarioToken)
        scenario_id(fileIdx) = fileIdx;
    else
        scenario_id(fileIdx) = str2double(scenarioToken{1});
    end

    %% Store physics and truth values

    actual_class(fileIdx) = string(scene.target.class);

    received_power_dbm(fileIdx) = scene.receivedPowerDbm;
    input_snr_db(fileIdx) = scene.inputSnrDb;
    rcs_m2(fileIdx) = scene.target.rcs_m2;

    truth_range_m(fileIdx) = scene.target.range_m;
    truth_velocity_mps(fileIdx) = scene.target.velocity_mps;

    %% Automatically derive CA-CFAR configuration
   

    desiredTrainingRange_m = 30;
    desiredGuardRange_m = 15;

    desiredTrainingVelocity_mps = 14;
    desiredGuardVelocity_mps = 5;

    rangeBinSize_m = ...
        params.c / (2 * params.B);

    velocityBinSize_mps = ...
        params.lambda * params.PRF / ...
        (2 * params.Nchirps);

    cfg.numTrainRange = max( ...
        1, ...
        round(desiredTrainingRange_m / rangeBinSize_m));

    cfg.numGuardRange = max( ...
        1, ...
        round(desiredGuardRange_m / rangeBinSize_m));

    cfg.numTrainDoppler = max( ...
        1, ...
        round(desiredTrainingVelocity_mps / velocityBinSize_mps));

    cfg.numGuardDoppler = max( ...
        1, ...
        round(desiredGuardVelocity_mps / velocityBinSize_mps));

    cfg.Pfa = 1e-4;
    cfg.minTrainingCells = 40;

    %% MTI clutter removal

    % Remove the slow-time mean from each fast-time sample
    iqMti = iq - mean(iq, 2);

    %% Hann windowing

    rangeWin = local_hann(params.Nfast);
    dopplerWin = local_hann(params.Nchirps).';

    iqWindowed = ...
        iqMti .* ...
        rangeWin .* ...
        dopplerWin;

    %% Range-Doppler processing

    rangeFFT = ...
        fft(iqWindowed, params.Nfast, 1);

    rdMap = ...
        fftshift( ...
            fft(rangeFFT, params.Nchirps, 2), ...
            2);

    % Retain positive FMCW range bins
    halfIdx = 1:floor(params.Nfast / 2);

    rdMapPositiveRange = rdMap(halfIdx, :);
    rdPower = abs(rdMapPositiveRange).^2;

    %% Range and radial-velocity axes

    beatFrequencyAxis = ...
        (halfIdx - 1) * ...
        params.fs / ...
        params.Nfast;

    rangeAxis = ...
        beatFrequencyAxis * ...
        params.c / ...
        (2 * params.S);

    dopplerFrequencyAxis = ...
        (-params.Nchirps/2 : params.Nchirps/2 - 1) * ...
        (params.PRF / params.Nchirps);

    velocityAxis = ...
        dopplerFrequencyAxis * ...
        params.lambda / 2;

    %% Edge-aware 2D CA-CFAR

    [detectionMask, ~, noiseMap] = ca_cfar_2d_edge( ...
        rdPower, ...
        cfg.numTrainRange, ...
        cfg.numTrainDoppler, ...
        cfg.numGuardRange, ...
        cfg.numGuardDoppler, ...
        cfg.Pfa, ...
        cfg.minTrainingCells);

    %% Suppress only the zero-range/DC bin

    detectionMask(1, :) = false;

    total_cfar_cells(fileIdx) = nnz(detectionMask);

    %% Group adjacent CFAR cells into clusters

    clusters = find_detection_clusters( ...
        detectionMask, ...
        rdPower, ...
        noiseMap, ...
        rangeAxis, ...
        velocityAxis);

    num_clusters(fileIdx) = numel(clusters);

    %% Handle scenarios with no CFAR cluster

    if isempty(clusters)

        fprintf( ...
            ['Scenario %03d | %-6s | NO DETECTION | ' ...
             'input SNR=%+6.2f dB | ' ...
             'truth R=%7.2f m, v=%+7.2f m/s\n'], ...
            scenario_id(fileIdx), ...
            char(actual_class(fileIdx)), ...
            input_snr_db(fileIdx), ...
            truth_range_m(fileIdx), ...
            truth_velocity_mps(fileIdx));

        continue;

    end

    %% Select the strongest detected cluster
    %
    % This selection uses only measured Range-Doppler power. It does not
    % use the simulated truth.

    clusterPeakPowers = [clusters.peakPower];

    [~, selectedClusterIdx] = max(clusterPeakPowers);

    target = clusters(selectedClusterIdx);

    detected(fileIdx) = true;

    %% Extract radar features

    estimated_range_m(fileIdx) = ...
        target.peakRange;

    estimated_velocity_mps(fileIdx) = ...
        target.peakVel;

    absolute_speed_mps(fileIdx) = ...
        abs(target.peakVel);

    peak_power_db(fileIdx) = ...
        10 * log10(target.peakPower + eps);

    estimated_snr_db(fileIdx) = ...
        target.estimatedSnrDb;

    cluster_cfar_cells(fileIdx) = ...
        target.numCells;

    %% Calculate truth-verification errors

    range_error_m(fileIdx) = ...
        estimated_range_m(fileIdx) - ...
        truth_range_m(fileIdx);

    velocity_error_mps(fileIdx) = ...
        estimated_velocity_mps(fileIdx) - ...
        truth_velocity_mps(fileIdx);

    %% Print one summary line per scenario

    fprintf( ...
        ['Scenario %03d | %-6s | DETECTED | ' ...
         'input SNR=%+6.2f dB | ' ...
         'truth R=%7.2f m, v=%+7.2f m/s | ' ...
         'est R=%7.2f m, v=%+7.2f m/s | ' ...
         'processed SNR=%6.2f dB\n'], ...
        scenario_id(fileIdx), ...
        char(actual_class(fileIdx)), ...
        input_snr_db(fileIdx), ...
        truth_range_m(fileIdx), ...
        truth_velocity_mps(fileIdx), ...
        estimated_range_m(fileIdx), ...
        estimated_velocity_mps(fileIdx), ...
        estimated_snr_db(fileIdx));

end

%% ------------------------------------------------------------------------
% Build feature table
% -------------------------------------------------------------------------

featureTable = table( ...
    scenario_id, ...
    actual_class, ...
    received_power_dbm, ...
    input_snr_db, ...
    rcs_m2, ...
    detected, ...
    estimated_range_m, ...
    estimated_velocity_mps, ...
    absolute_speed_mps, ...
    peak_power_db, ...
